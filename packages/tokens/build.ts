// Builds dist/tokens.css and dist/tokens.ts from the DTCG sources in tokens/.
//
// Style Dictionary runs once per theme. Both runs share the primitives and the
// theme-independent semantic tokens (semantic/base.json); only the themed set
// (semantic/light.json or semantic/dark.json) differs.

import { mkdir, writeFile } from "node:fs/promises";
import StyleDictionary from "style-dictionary";
import type { TransformedToken } from "style-dictionary/types";

const THEMES = ["light", "dark"] as const;
type Theme = (typeof THEMES)[number];

const OUT_DIR = new URL("./dist/", import.meta.url);

async function loadTokens(theme: Theme): Promise<TransformedToken[]> {
  const sd = new StyleDictionary({
    source: [
      "tokens/primitive/**/*.json",
      "tokens/semantic/base.json",
      `tokens/semantic/${theme}.json`,
    ],
    usesDtcg: true,
    log: { verbosity: "verbose", warnings: "error" },
    platforms: { css: { transformGroup: "css" } },
  });
  const { allTokens } = await sd.getPlatformTokens("css");
  return allTokens;
}

const isThemed = (t: TransformedToken) =>
  /semantic[\\/](light|dark)\.json$/.test(t.filePath);
const isPrimitive = (t: TransformedToken) =>
  /[\\/]primitive[\\/]/.test(t.filePath);
const dotName = (t: TransformedToken) => t.path.join(".");
const cssVar = (t: TransformedToken) => `--${t.name}`;
const value = (t: TransformedToken) => String(t.$value);

/** Emits `var(--x)` for a token that aliases another, so the CSS keeps the alias chain. */
function cssValue(
  t: TransformedToken,
  byPath: Map<string, TransformedToken>,
): string {
  const original: unknown = t.original.$value;
  const ref =
    typeof original === "string" ? /^\{([^}]+)\}$/.exec(original) : null;
  const target = ref?.[1] ? byPath.get(ref[1]) : undefined;
  return target ? `var(${cssVar(target)})` : value(t);
}

function assertParity(
  light: TransformedToken[],
  dark: TransformedToken[],
): void {
  const names = (ts: TransformedToken[]) =>
    new Set(ts.filter(isThemed).map(dotName));
  const l = names(light);
  const d = names(dark);
  const missing = [
    ...[...l].filter((n) => !d.has(n)).map((n) => `${n} (missing from dark)`),
    ...[...d].filter((n) => !l.has(n)).map((n) => `${n} (missing from light)`),
  ];
  if (missing.length > 0) {
    throw new Error(
      `Light and dark themes must define the same tokens:\n  ${missing.join("\n  ")}`,
    );
  }
}

function buildCss(light: TransformedToken[], dark: TransformedToken[]): string {
  const byPath = new Map(light.map((t) => [dotName(t), t]));
  const decl = (t: TransformedToken) =>
    `  ${cssVar(t)}: ${cssValue(t, byPath)};`;
  return [
    "/* Generated by packages/tokens/build.ts. Do not edit. */",
    "",
    ':root,\n[data-theme="light"] {',
    "  color-scheme: light;",
    ...light.map(decl),
    "}",
    "",
    '[data-theme="dark"] {',
    "  color-scheme: dark;",
    ...dark.filter(isThemed).map(decl),
    "}",
    "",
  ].join("\n");
}

/** "font.size" -> "fontSize", "border.width" -> "borderWidth" */
const groupKey = (path: string[]) =>
  path
    .slice(0, -1)
    .join("-")
    .replace(/-(\w)/g, (_, c: string) => c.toUpperCase());

function buildTs(light: TransformedToken[], dark: TransformedToken[]): string {
  const token = (t: TransformedToken) => ({
    name: dotName(t),
    cssVar: cssVar(t),
    value: value(t),
  });
  const darkByName = new Map(dark.map((t) => [dotName(t), t]));

  const palettes = new Map<string, ReturnType<typeof token>[]>();
  for (const t of light.filter(isPrimitive)) {
    const palette = t.path[1] ?? "";
    palettes.set(palette, [...(palettes.get(palette) ?? []), token(t)]);
  }

  const themedColors = light.filter(isThemed).map((t) => ({
    name: dotName(t),
    cssVar: cssVar(t),
    light: value(t),
    dark: value(darkByName.get(dotName(t)) ?? t),
  }));

  const scales = new Map<string, ReturnType<typeof token>[]>();
  for (const t of light.filter((t) => !isPrimitive(t) && !isThemed(t))) {
    const key = groupKey(t.path);
    scales.set(key, [...(scales.get(key) ?? []), token(t)]);
  }

  const json = (v: unknown) => JSON.stringify(v, null, 2);
  return [
    "// Generated by packages/tokens/build.ts. Do not edit.",
    "",
    "export interface Token {",
    "  /** Dotted token path, e.g. `color.neutral.500`. */",
    "  readonly name: string;",
    "  /** CSS custom property, e.g. `--color-neutral-500`. */",
    "  readonly cssVar: string;",
    "  readonly value: string;",
    "}",
    "",
    "export interface ThemedToken {",
    "  readonly name: string;",
    "  readonly cssVar: string;",
    "  readonly light: string;",
    "  readonly dark: string;",
    "}",
    "",
    "export interface Palette {",
    "  readonly name: string;",
    "  readonly tokens: readonly Token[];",
    "}",
    "",
    "/** Primitive color palettes. For display only; components use semantic tokens. */",
    `export const palettes: readonly Palette[] = ${json([...palettes].map(([name, tokens]) => ({ name, tokens })))};`,
    "",
    "/** Semantic colors with their light and dark values. */",
    `export const themedColors: readonly ThemedToken[] = ${json(themedColors)};`,
    "",
    ...[...scales].flatMap(([key, tokens]) => [
      `export const ${key}: readonly Token[] = ${json(tokens)};`,
      "",
    ]),
  ].join("\n");
}

const [light, dark] = await Promise.all(THEMES.map(loadTokens));
if (!light || !dark) throw new Error("unreachable");
assertParity(light, dark);

await mkdir(OUT_DIR, { recursive: true });
await Promise.all([
  writeFile(new URL("tokens.css", OUT_DIR), buildCss(light, dark)),
  writeFile(new URL("tokens.ts", OUT_DIR), buildTs(light, dark)),
]);
console.log(
  `tokens: wrote ${light.length} tokens (${dark.filter(isThemed).length} themed) to dist/`,
);
